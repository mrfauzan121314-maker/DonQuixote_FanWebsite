"""Read the JSON data files and resolve asset paths for a page depth."""

import json
from functools import lru_cache

from .config import BASE_URL, DATA


@lru_cache(maxsize=None)
def identities():
    return json.loads((DATA / "identities.json").read_text(encoding="utf-8"))


@lru_cache(maxsize=None)
def egos():
    return json.loads((DATA / "ego.json").read_text(encoding="utf-8"))


def identity(identity_id):
    for entry in identities():
        if entry["id"] == identity_id:
            return entry
    raise KeyError(f"identity tidak ditemukan: {identity_id}")


def identity_cards():
    return sorted(identities(), key=lambda e: e["card"]["order"])


def absolute(path):
    """Turn a site-relative path into an absolute URL when SITE_URL is configured."""
    if not path:
        return ""
    if path.startswith(("http://", "https://")):
        return path
    if not BASE_URL:
        return path
    return f"{BASE_URL}/{path.lstrip('/')}"


def at(root, path):
    """Prefix a site-relative asset path for a page living `root` levels deep."""
    return path if not root else f"{root}{path}"


def thumb(path):
    """Smaller variant of a detail hero (640px wide) generated by optimize-assets.py."""
    return path.replace(".webp", "-640.webp")
